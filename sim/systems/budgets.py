"""System budgets for FrutaMIDI (systems-engineer). Revision 2 (T-010), replaces the T-009 version.

Every input carries a label: SOURCE (id in requirements/SOURCES_SYSTEMS.md), ASSUMPTION (with the
reason) or a CALCULATION from those. Ranges are carried as (low, high) and propagated as
worst-case intervals. Run with the project venv:

    .venv/bin/python sim/systems/budgets.py > sim/systems/budgets.out

Changes from T-009: Pico datasheet values (S-01, S-16) replace secondary-source and assumed values;
PCB I2C pull-ups R13/R14 4k7 and electrode series resistors R1..R12 3k3 (T-050) included; latency
recomputed from the I2C transactions the current firmware actually makes (M1 burst read, T-040) at
400 kHz and 100 kHz; targets per ADR-007 (worst case <= 15 ms, jitter <= 10 ms).
"""
import sys

checks = []


def check(name, ok, detail):
    checks.append(ok)
    print("%s  %s :: %s" % ("PASS" if ok else "FAIL", name, detail))


def rng(lo, hi=None):
    return (lo, lo if hi is None else hi)


def add(*rs):
    return (sum(r[0] for r in rs), sum(r[1] for r in rs))


def fmt(r, unit, nd=3):
    return "%.*f .. %.*f %s" % (nd, r[0], nd, r[1], unit)


def par(*rs):
    return 1.0 / sum(1.0 / r for r in rs)


# =============================================================================================
# (a) Current budget: 3V3 rail (Pico 3V3(OUT), pin 36) and VBUS
# =============================================================================================
print("=" * 90)
print("(a) CURRENT BUDGET")
print("=" * 90)
V33 = 3.3          # V, SOURCE S-01 sec. 2.1 ("3V3 is the main 3.3 V supply ... generated by the on-board SMPS")

loads = []


def load(name, r, label, per_module=False):
    loads.append((name, r, label, per_module))


load("MPR121 IC (ESI 1 ms)", rng(0.10, 1.0), "SOURCE S-04 (393 uA avg @ CDC 63 uA, 1 mA peak); low end ASSUMPTION", True)
load("Module LDO quiescent", rng(0.02, 0.10), "ASSUMPTION (MIC5225 / AP2112K datasheets not read)", True)
load("Module power LED (R7 1k)", ((V33 - 2.2) / 1.0, (V33 - 1.8) / 1.0), "CALCULATION (3.3-Vf)/1k, Vf 1.8..2.2 V ASSUMPTION", True)
load("Module IRQ LED (10k)", rng(0.0, (V33 - 1.8) / 10.0), "CALCULATION, worst case INT held low", True)
load("Module I2C pull-ups (4 x 10k, lines low)", rng(0.0, 4 * V33 / 10.0), "CALCULATION, worst case (S-06/S-07)", True)
load("PCB I2C pull-ups R13/R14 4k7 (lines low)", rng(0.0, 2 * V33 / 4.7), "CALCULATION; PCB build only (kicad_pcb R13/R14)")
load("RP2040 I2C internal pull-ups", rng(0.0, 2 * V33 / 50.0), "CALCULATION, R >= 50 kOhm ASSUMPTION (RP2040 datasheet not read)")
load("Octave pot 10k +-20 %", (V33 / 12.0, V33 / 8.0), "CALCULATION V/R")
load("Button pull-up (pressed)", rng(0.0, V33 / 50.0), "CALCULATION, R ASSUMPTION")
load("Electrode series R1..R12 3k3", rng(0.0, 0.0), "CALCULATION: no DC path (MPR121 charge current only, inside IDD)")

ext_1 = add(*[r for _, r, _, _ in loads])
ext_mod = add(*[r for _, r, _, m in loads if m])
ext_2 = add(ext_1, ext_mod)
for n, r, lab, _ in loads:
    print("  %-42s %-22s %s" % (n, fmt(r, "mA"), lab))
print("  %-42s %s  CALCULATION (sum)" % ("External 3V3 load, 1 sensor", fmt(ext_1, "mA")))
print("  %-42s %s  CALCULATION (+ second module, breadboard)" % ("External 3V3 load, 2 sensors", fmt(ext_2, "mA")))

I33_LIMIT = 300.0   # mA, SOURCE S-01 sec. 2.1: "recommended to keep the load on this pin less than 300 mA"
check("A1 3V3 external load <= 300 mA with >= 50 % margin", ext_2[1] <= 0.5 * I33_LIMIT,
      "worst %.2f mA (2 sensors) vs %.0f mA, margin %.1f %%" % (ext_2[1], I33_LIMIT, 100 * (1 - ext_2[1] / I33_LIMIT)))

# Pico board's own VBUS current. Datasheet anchors (SOURCE):
#   S-01 Table 3: Pico BOOTSEL, USB active, 25 C mean 9.9 mA; Table 1/2 'Popcorn' 86.5..95.5 mA incl. VGA board.
#   S-16 Table 2: Pico 2 hello_usb 12.74 mA, USB boot peak 14.26 mA.
# Neither datasheet tabulates a CPU-busy USB-MIDI loop at the arduino-pico default clock
# (first freq menu entry 200 MHz, S-09 boards.txt). Upper bounds stay ASSUMPTION; lower bounds are SOURCE.
PICO_BOARD_MA = {
    "Pico": ((9.9, 45.0), "low SOURCE S-01 T3 (9.9 mA BOOTSEL USB active); high ASSUMPTION"),
    "Pico W": ((9.9, 60.0), "low SOURCE S-01 T3 (Pico, no radio); high ASSUMPTION (CYW43 present, radio unused; Pico W datasheet not read)"),
    "Pico 2": ((12.74, 50.0), "low SOURCE S-16 T2 (hello_usb 12.74 mA); high ASSUMPTION"),
    "Pico 2 W": ((12.74, 65.0), "low SOURCE S-16 T2; high ASSUMPTION (Pico 2 W datasheet not read)"),
}
ETA = rng(0.80, 0.90)         # ASSUMPTION: RT6150/RT6154 efficiency at light load (value not in S-01/S-16 text)
VDIODE = rng(0.25, 0.45)      # ASSUMPTION: S-01 sec. 4.4 confirms a Schottky D1 VBUS->VSYS but gives no drop value
VBUS_USB = rng(4.40, 5.50)    # SOURCE S-10 (low-power port min, ECN max)
VBUS_PICO = rng(4.50, 5.50)   # SOURCE S-01 sec. 2.3 / S-16: "VBUS 5 V +- 10%"
VSYS_LIM = rng(1.8, 5.5)      # SOURCE S-01 sec. 2.1 / 2.3: VSYS 1.8 V .. 5.5 V
vsys = (VBUS_USB[0] - VDIODE[1], VBUS_USB[1] - VDIODE[0])
print("  VSYS range = %s  CALCULATION VBUS - Vdiode" % fmt(vsys, "V", 2))
I_DECLARED = 100.0            # mA, SOURCE S-11
for name, (pico, lab) in PICO_BOARD_MA.items():
    ext_hi = V33 * ext_2[1] / (ETA[0] * vsys[0])
    ext_lo = V33 * ext_1[0] / (ETA[1] * vsys[1])
    tot = (pico[0] + ext_lo, pico[1] + ext_hi)
    check("A2 VBUS current <= 100 mA declared [%s]" % name, tot[1] <= I_DECLARED,
          "%s (board %s: %s) ; margin %.0f %%" % (fmt(tot, "mA", 1), fmt(pico, "mA", 1), lab, 100 * (1 - tot[1] / I_DECLARED)))
check("A3 VSYS within 1.8..5.5 V over USB VBUS 4.40..5.50 V", vsys[0] >= VSYS_LIM[0] and vsys[1] <= VSYS_LIM[1],
      "VSYS %s" % fmt(vsys, "V", 2))
check("A3b USB VBUS range inside Pico recommended VBUS 4.5..5.5 V", VBUS_USB[0] >= VBUS_PICO[0],
      "USB low-power port min %.2f V < Pico recommended %.2f V (VSYS margin above 1.8 V stays %.2f V)"
      % (VBUS_USB[0], VBUS_PICO[0], vsys[0] - VSYS_LIM[0]))
vdd = (V33 * 0.97 - 0.10, V33 * 1.03)
check("A4 MPR121 VDD inside 2.0..3.6 V (S-04 Table 5)", vdd[0] >= 2.0 and vdd[1] <= 3.6, "VDD %s (rail +-3 %%, LDO dropout <= 0.1 V ASSUMPTION)" % fmt(vdd, "V", 2))

# ADC / octave pot (S-01 sec. 4.3: ADC_AVDD from 3V3 through 201 Ohm into 2.2 uF; ~150 uA draw -> ~30 mV offset)
adc_offset_v = 150e-6 * 200.0
zone_v = V33 / 5
hyst_v = 0.7 * zone_v
print("  ADC: offset %.3f V (SOURCE S-01 4.3), zone %.3f V, hysteresis %.3f V, offset = %.1f %% of hysteresis  CALCULATION"
      % (adc_offset_v, zone_v, hyst_v, 100 * adc_offset_v / hyst_v))
check("A5 ADC offset < 25 % of the pot hysteresis band", adc_offset_v < 0.25 * hyst_v, "%.3f V vs %.3f V" % (adc_offset_v, 0.25 * hyst_v))
# GP26/GP27 are ADC-capable pins with a reverse diode to IOVDD (S-01 sec. 4.2): input <= IOVDD + 0.3 V.
# PCB pull-ups (R13/R14, module host side) go to the same +3V3 rail -> no over-voltage, no back-feed. CALCULATION.
check("A6 I2C on ADC-capable GP26/27: pull-up rail = IOVDD", True, "R13/R14 and module VIN/VCC are on +3V3 (Pico pin 36)")
assert abs(V33 / 10.0 - 0.33) < 1e-12     # known-answer smoke case (T-006)

# =============================================================================================
# (b) Touch-to-MIDI latency budget (device side) with the firmware as it is now (T-040)
# =============================================================================================
print()
print("=" * 90)
print("(b) LATENCY BUDGET (firmware T-040: M1 burst read, non-blocking LED)")
print("=" * 90)
FFI, SFI, ESI_MS, DT, N_CH = 6, 4, 1.0, 0, 12     # SOURCE S-08 (CONFIG1 0x10, CONFIG2 0x20, DEBOUNCE 0, ECR 0x8C)
assert abs(34 * (32e-3 + 32e-3) * 13 - 28.288) < 1e-9   # S-04 sec. 5.8 example "28 mS"
CDT_US = [0.5, 1, 2, 4, 8, 16, 32]


def esi_eff(cdt_us):
    return max(ESI_MS, FFI * 2 * cdt_us * N_CH / 1000.0)


V_TL = 180 / 256 * V33
I_MAX = 63e-6


def cdt_for(c_pf):
    t_us = c_pf * 1e-12 * V_TL / I_MAX * 1e6
    for c in CDT_US:
        if c >= t_us:
            return c
    return None


# I2C transaction model. A register read is
#   START, addr+W (9 bits), register (9), Sr, addr+R (9), n data bytes (9 each), STOP
# = 9 * (3 + n) + 3 bit times (START/Sr/STOP counted as one bit time each).
def read_bits(n):
    return 9 * (3 + n) + 3


# Transactions made per loop by the current firmware (quoted in reports/systems/budgets.md):
#   every loop, per sensor : sensors[s].touched()  -> readRegister16(0x00): 1 register byte, 2 data bytes
#   aftertouch pass (every AT_INTERVAL_MS = 15 ms, only if a pad is active), per sensor:
#       readRegisters(addr, 0x04, filt, 24) and readRegisters(addr, 0x1E, base, 12)
TX_TOUCHED = [2]
TX_AT_PASS = [24, 12]
assert read_bits(2) == 48 and read_bits(24) == 246 and read_bits(12) == 138
SW_OVH = rng(10.0, 40.0)        # us per transaction, ASSUMPTION (Wire/BusIO software + FIFO handling)
T_MISC = rng(20.0, 100.0)       # us per loop, ASSUMPTION (midiTask, button, pot, LED, MIDI enqueue of up to 12 messages)
T_USB = rng(0.0, 1.0)           # ms, ASSUMPTION: next 1 ms full-speed frame; tud_task is IRQ-driven (S-11)
TARGET_WORST_MS = 15.0          # ADR-007 D-1
TARGET_JITTER_MS = 10.0         # ADR-007 D-1


def tx_us(nbytes, f):
    return (read_bits(nbytes) / f * 1e6 + SW_OVH[0], read_bits(nbytes) / f * 1e6 + SW_OVH[1])


def loop_us(f, sensors, at_pass):
    lo = hi = 0.0
    for _ in range(sensors):
        for n in TX_TOUCHED + (TX_AT_PASS if at_pass else []):
            a, b = tx_us(n, f)
            lo, hi = lo + a, hi + b
    return lo + T_MISC[0], hi + T_MISC[1]


def latency(c_pf, f, sensors):
    cdt = cdt_for(c_pf)
    e = esi_eff(cdt)
    sense = (SFI * e, 2 * SFI * e + DT * SFI * e)       # 1..2 status-update periods (ASSUMPTION on filter model)
    lp = loop_us(f, sensors, True)                      # worst loop includes the aftertouch pass
    best = sense[0] + 0.0 + T_USB[0]
    worst = sense[1] + lp[1] / 1000.0 + T_USB[1]
    return cdt, e, best, worst


for f in (400e3, 100e3):
    print("  f_SCL = %3.0f kHz: touched() %s, AT pass (24 B + 12 B) %s, loop idle %s, loop with AT pass %s  CALCULATION"
          % (f / 1e3, fmt(tx_us(2, f), "us", 0), fmt(add(tx_us(24, f), tx_us(12, f)), "us", 0),
             fmt(loop_us(f, 1, False), "us", 0), fmt(loop_us(f, 1, True), "us", 0)))

print()
print("  %-7s %-5s %-8s %-7s %-12s %-12s %-12s" % ("f_SCL", "sens", "C [pF]", "CDT", "best [ms]", "worst [ms]", "jitter [ms]"))
table = {}
for f in (400e3, 100e3):
    for sensors in (1, 2):
        for c_pf in (20, 100, 200, 300, 500):
            cdt, e, best, worst = latency(c_pf, f, sensors)
            table[(f, sensors, c_pf)] = (best, worst)
            print("  %-7s %-5d %-8d %-7s %-12.2f %-12.2f %-12.2f"
                  % ("%.0fk" % (f / 1e3), sensors, c_pf, "%gus" % cdt, best, worst, worst - best))

for f in (400e3, 100e3):
    for sensors in (1, 2):
        b, w = table[(f, sensors, 100)]
        tag = "%.0f kHz, %d sensor%s, C <= 100 pF" % (f / 1e3, sensors, "" if sensors == 1 else "s")
        check("B1 worst <= 15 ms [%s]" % tag, w <= TARGET_WORST_MS, "worst %.2f ms" % w)
        check("B2 jitter <= 10 ms [%s]" % tag, w - b <= TARGET_JITTER_MS, "jitter %.2f ms" % (w - b))

# Largest electrode capacitance that still meets both targets (1 sensor), per clock
for f in (400e3, 100e3):
    ok_c = [c for c in range(10, 1201, 10) if cdt_for(c) is not None
            and (lambda r: r[3] <= TARGET_WORST_MS and r[3] - r[2] <= TARGET_JITTER_MS)(latency(c, f, 1))]
    print("  DESIGN LIMIT %.0f kHz, 1 sensor: targets met for electrode C <= %d pF  CALCULATION" % (f / 1e3, max(ok_c)))

# Blocking: LED feedback is non-blocking since T-040 (fm_blink.h). Remaining blocking calls during play: none;
# recalibrate() (user-requested long press) re-runs Adafruit_MPR121::begin(). Count of its I2C transactions
# (S-08 begin(), writeRegister(): ECR read + [ECR=0, write, ECR restore] unless reg is ECR or 0x73..0x7A):
WR_STOP = 1 + 24 + 11 + 3 + 4      # SOFTRESET, 24 thresholds, 11 filter regs, DEBOUNCE/CONFIG1/CONFIG2, 4 autoconfig regs
WR_NOSTOP = 2                      # two ECR writes
bits_wr = 9 * 3 + 2                # START addr reg data STOP
bits_rd1 = read_bits(1)
recal_bits = WR_STOP * (bits_rd1 + 3 * bits_wr) + WR_NOSTOP * (bits_rd1 + bits_wr) + bits_rd1 + 12
recal_tx = WR_STOP * 4 + WR_NOSTOP * 2 + 2
for f in (400e3, 100e3):
    t = (recal_bits / f * 1e3 + recal_tx * SW_OVH[0] / 1e3 + 1.0, recal_bits / f * 1e3 + recal_tx * SW_OVH[1] / 1e3 + 1.0)
    print("  recalibrate() per sensor at %.0f kHz: %d transactions, %s (incl. 1 ms reset delay)  CALCULATION" % (f / 1e3, recal_tx, fmt(t, "ms", 1)))

# I2C rise time (S-13 not read: fast mode t_r <= 300 ns, standard mode <= 1000 ns, t_r = 0.8473 R C)
R_INT = 50e3                                   # ASSUMPTION
R_BB = par(10e3, R_INT)                        # breadboard: module host-side 10k || RP2040 internal
R_PCB = par(4.7e3, 10e3, R_INT)                # PCB: + R13/R14 4k7
for name, r in (("breadboard", R_BB), ("PCB", R_PCB)):
    print("  I2C %-10s R_eff %.2f kOhm: C_b max %.1f pF @400 kHz, %.1f pF @100 kHz  CALCULATION"
          % (name, r / 1e3, 300e-9 / (0.8473 * r) * 1e12, 1000e-9 / (0.8473 * r) * 1e12))
CB = rng(20e-12, 60e-12)                       # ASSUMPTION
for name, r in (("breadboard", R_BB), ("PCB", R_PCB)):
    for f, lim in ((400e3, 300.0), (100e3, 1000.0)):
        tr = 0.8473 * r * CB[1] * 1e9
        check("B3 I2C rise time [%s, %.0f kHz, C_b <= 60 pF]" % (name, f / 1e3), tr <= lim, "t_r %.0f ns <= %.0f ns" % (tr, lim))
# Sink current with PCB pull-ups when the MPR121 side pulls low through the BSS138 (both sides' pull-ups):
i_sink = V33 / R_PCB * 1e3 + V33 / 10e3 * 1e3
check("B4 I2C low-level sink current <= 3 mA (S-13 fast-mode VOL spec)", i_sink <= 3.0, "%.2f mA" % i_sink)

# Electrode series resistor 3k3 (T-050): RC and IR drop against the MPR121 charge (S-04 CDC/CDT)
R_S = 3.3e3
for c_pf in (20, 100, 500, 1000):
    cdt = cdt_for(c_pf) or 32
    tau = R_S * c_pf * 1e-12 * 1e6
    print("  series 3k3: C %4d pF, tau %.2f us vs CDT %g us (ratio %.2f); IR at 63 uA = %.3f V  CALCULATION"
          % (c_pf, tau, cdt, tau / cdt, 63e-6 * R_S))

