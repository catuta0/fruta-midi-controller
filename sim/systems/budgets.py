TARGET_JITTER_MS = 10.0         # ADR-007 D-1


def tx_us(nbytes, f):
    return (read_bits(nbytes) / f * 1e6 + SW_OVH[0], read_bits(nbytes) / f * 1e6 + SW_OVH[1])


def loop_us(f, sensors, at_pass):
    lo = hi = 0.0
    for _ in range(sensors):
        for n in TX_TOUCHED + (TX_AT_PASS if at_pass else []):
            a, b = tx_us(n, f)
            lo, hi = lo + a, hi + b
    return lo + T_MISC[0], hi + T_MISC[1]


def latency(c_pf, f, sensors):
    cdt = cdt_for(c_pf)
    e = esi_eff(cdt)
    sense = (SFI * e, 2 * SFI * e + DT * SFI * e)       # 1..2 status-update periods (ASSUMPTION on filter model)
    lp = loop_us(f, sensors, True)                      # worst loop includes the aftertouch pass
    best = sense[0] + 0.0 + T_USB[0]
    worst = sense[1] + lp[1] / 1000.0 + T_USB[1]
    return cdt, e, best, worst


